# export_context.py — Export all context files as a single portable markdown
# ─────────────────────────────────────────────────────────────────────────────

def export_context(input_dir, output_path):
    """Bundle all .ai-context/ files into one portable document."""
    src = Path(input_dir)
    sections = []

    order = [
        "SESSION-STARTER.md",
        "CONTEXT.md",
        "DECISIONS.md",
        "PATTERNS.md",
        "STYLE.md",
        "ANTI-PATTERNS.md",
    ]

    for fname in order:
        fpath = src / fname
        if fpath.exists():
            content = fpath.read_text(encoding="utf-8")
            sections.append(f"---\n# 📄 {fname}\n\n{content}")

    # Any extra files not in order
    for fpath in sorted(src.glob("*.md")):
        if fpath.name not in order and fpath.name != "UPDATE-LOG.md":
            content = fpath.read_text(encoding="utf-8")
            sections.append(f"---\n# 📄 {fpath.name}\n\n{content}")

    header = f"""# AI Context Export
*Exported: {now_date()}*
*Generated by Vibe Context Architect*

This file contains the complete AI context for this project.
Paste it at the start of an AI chat session or upload as a document.

"""
    combined = header + "\n\n".join(sections)

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)
    Path(output_path).write_text(combined, encoding="utf-8")
    print(f"  → Exported to: {output_path}", file=sys.stderr)
    print(f"  → Size: {len(combined)} chars (~{len(combined)//4} tokens)", file=sys.stderr)
    return output_path


if __name__ == "__main__":
    # When run as export_context.py
    import sys
    if len(sys.argv) > 1 and sys.argv[1] == "--export":
        parser = argparse.ArgumentParser()
        parser.add_argument("--input", required=True)
        parser.add_argument("--output", required=True)
        args = parser.parse_args(sys.argv[2:])
        export_context(args.input, args.output)
