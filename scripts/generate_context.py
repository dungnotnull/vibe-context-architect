def generate_session_starter_md(scan, configs, conventions, antipatterns_md):
    project = scan.get("project_name", "My Project")
    stack = scan.get("stack", {})
    conv = conventions.get("conventions", {}) if conventions else {}

    # Format stack one-liner
    parts = []
    for k in ["frontend", "language", "database", "auth", "styling", "state"]:
        v = stack.get(k)
        if v:
            if isinstance(v, list): v = " + ".join(v)
            parts.append(str(v))
    stack_line = " · ".join(parts[:6])

    # Compact directory map (top 8 dirs)
    dir_map = scan.get("directory_map", {})
    dir_lines = [f"  {d}" for d in list(dir_map.keys())[:8] if not d.startswith(".")]

    # Top conventions
    naming = conv.get("naming", {})
    code_style = conv.get("code_style", {})
    structure = conv.get("structure", {})

    top_conventions = []
    for k, v in list(naming.items())[:4]:
        if v: top_conventions.append(f"- {k.replace('_', ' ').title()}: `{v}`")
    for k, v in list(code_style.items())[:3]:
        if v: top_conventions.append(f"- {k.replace('_', ' ').title()}: {v}")
    for k, v in list(structure.items())[:2]:
        if v: top_conventions.append(f"- {k.replace('_', ' ').title()}: {v}")

    # Top 5 anti-patterns (extract from ANTI-PATTERNS.md)
    anti_lines = []
    for line in antipatterns_md.splitlines():
        if line.startswith("## ❌"):
            title = line.replace("## ❌ ", "").strip()
            # Remove leading number
            import re
            title = re.sub(r"^\d+\. ", "", title)
            anti_lines.append(f"- ❌ {title}")
        if len(anti_lines) >= 5:
            break

    # Prisma models
    prisma = configs.get("prisma", {})
    models_line = ""
    if prisma.get("models"):
        models_line = f"\n## Data Models\nKey entities: {', '.join(f'`{m}`' for m in prisma['models'][:6])}"

    content = f"""# {project} — AI Context Starter

**Copy and paste this at the start of any new AI chat session.**

---

You are working on **{project}**.

## Stack
{stack_line}

## Project Structure
```
{chr(10).join(dir_lines)}
```
{models_line}

## Key Conventions (always follow)
{chr(10).join(top_conventions[:8]) or "- See `.ai-context/STYLE.md` for full conventions"}

## ❌ Never Do These
{chr(10).join(anti_lines[:5]) or "- See `.ai-context/ANTI-PATTERNS.md`"}

## Current Task
*[Describe what you're working on here]*

---
Full context: `.ai-context/CONTEXT.md`
Patterns: `.ai-context/PATTERNS.md`
Decisions: `.ai-context/DECISIONS.md`
"""

    # Trim to ~800 tokens if too long
    token_count = count_tokens_approx(content)
    if token_count > 900:
        # Trim conventions and anti-patterns
        content = content.replace(
            chr(10).join(top_conventions[:8]),
            chr(10).join(top_conventions[:5])
        )

    return content


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--scan", required=True)
    parser.add_argument("--configs", required=True)
    parser.add_argument("--annotations", required=True)
    parser.add_argument("--conventions", default=None)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    scan = load_json(args.scan)
    configs = load_json(args.configs)
    annotations = load_json(args.annotations)
    conventions = load_json(args.conventions) if args.conventions and Path(args.conventions).exists() else None

    out = args.output.rstrip("/")

    print(f"Generating context files for: {scan.get('project_name', '?')}", file=sys.stderr)

    # Generate all 6 files
    context_md = generate_context_md(scan, configs, conventions)
    save_text(context_md, f"{out}/CONTEXT.md")

    patterns_md = generate_patterns_md(scan, configs, conventions)
    save_text(patterns_md, f"{out}/PATTERNS.md")

    style_md = generate_style_md(scan, configs, conventions)
